defmodule AshClickhouse.BulkReturnTest do
  @moduledoc """
  The record `bulk_create/3` hands back: the values it carries and the bulk
  metadata Ash uses to match a returned record to the changeset that produced
  it.
  """

  use ExUnit.Case, async: false

  alias AshClickhouse.BulkReturnDomain
  alias AshClickhouse.BulkReturnResource
  alias AshClickhouse.DataLayer

  @at ~U[2024-01-02 03:04:05.123456Z]
  # Ash's `:naive_datetime` has second precision, so this is the value the
  # changeset holds and the value the record must carry back.
  @naive ~N[2024-01-02 03:04:05]
  @day ~D[2024-01-02]

  defp inserted_rows do
    receive do
      {:inserted, rows} -> rows
    after
      0 -> []
    end
  end

  defp changeset(attrs \\ %{}) do
    Ash.Changeset.for_create(
      BulkReturnResource,
      :create,
      Map.merge(%{at: @at, naive: @naive, day: @day, name: "n"}, attrs)
    )
  end

  describe "the values a bulk-written record carries" do
    test "a datetime attribute comes back as a DateTime" do
      assert {:ok, stream} = DataLayer.bulk_create(BulkReturnResource, [changeset()], [])
      assert [record] = Enum.to_list(stream)
      assert record.at == @at
      assert %DateTime{} = record.at
    end

    test "a naive datetime attribute comes back as a NaiveDateTime" do
      assert {:ok, stream} =
               DataLayer.bulk_create(BulkReturnResource, [changeset(%{naive: @naive})], [])

      assert [record] = Enum.to_list(stream)
      assert record.naive == @naive
      assert %NaiveDateTime{} = record.naive
    end

    test "a date attribute comes back as a Date" do
      assert {:ok, stream} = DataLayer.bulk_create(BulkReturnResource, [changeset()], [])
      assert [record] = Enum.to_list(stream)
      assert record.day == @day
      assert %Date{} = record.day
    end

    test "the encoded rows still reach the client unchanged" do
      assert {:ok, _stream} = DataLayer.bulk_create(BulkReturnResource, [changeset()], [])

      # id, at, naive, day, name, computed — `computed` is a column the
      # submitted row carries no value for.
      assert [[_id, at, naive, day, "n", nil]] = inserted_rows()
      assert at == "1704164645.123456"
      assert naive == "1704164645.000000"
      assert day == 19_724
    end

    test "a column the submitted row carries no value for has no value in the record" do
      assert {:ok, stream} = DataLayer.bulk_create(BulkReturnResource, [changeset()], [])
      assert [record] = Enum.to_list(stream)
      assert is_nil(record.computed)
    end

    test "the record's autogenerated primary key is the one that was written" do
      assert {:ok, stream} = DataLayer.bulk_create(BulkReturnResource, [changeset()], [])
      assert [record] = Enum.to_list(stream)

      assert [[id | _] | _] = inserted_rows()
      assert record.id == id
    end
  end

  describe "the bulk metadata a returned record carries" do
    test "a returned record carries the reference and index Ash matches on" do
      ref = make_ref()

      changeset =
        changeset()
        |> Ash.Changeset.put_context(:bulk_create, %{index: 3, ref: ref})

      assert {:ok, stream} = DataLayer.bulk_create(BulkReturnResource, [changeset], [])
      assert [record] = Enum.to_list(stream)

      assert record.__metadata__[:bulk_action_ref] == ref
      assert record.__metadata__[:bulk_create_index] == 3
    end

    test "a changeset without bulk context is left untagged rather than raising" do
      assert {:ok, stream} = DataLayer.bulk_create(BulkReturnResource, [changeset()], [])
      assert [record] = Enum.to_list(stream)
      assert record.__metadata__[:bulk_action_ref] == nil
    end
  end

  describe "Ash.bulk_create/4 asking for its records" do
    test "completes and returns one record per inserted row" do
      result =
        Ash.bulk_create(
          [%{at: @at, day: @day, name: "a"}, %{at: @at, day: @day, name: "b"}],
          BulkReturnResource,
          :create,
          domain: BulkReturnDomain,
          return_records?: true
        )

      assert result.status == :success
      assert length(result.records) == 2
      assert Enum.map(result.records, & &1.name) == ["a", "b"]
      assert Enum.all?(result.records, &match?(%DateTime{}, &1.at))
      assert Enum.all?(result.records, &match?(%Date{}, &1.day))
    end

    test "returns the records in the order the rows were submitted" do
      result =
        Ash.bulk_create(
          [%{name: "first"}, %{name: "second"}, %{name: "third"}],
          BulkReturnResource,
          :create,
          domain: BulkReturnDomain,
          return_records?: true
        )

      assert result.status == :success
      assert Enum.map(result.records, & &1.name) == ["first", "second", "third"]
    end

    test "a column the submitted row carries no value for has no value in the record" do
      result =
        Ash.bulk_create([%{name: "a"}], BulkReturnResource, :create,
          domain: BulkReturnDomain,
          return_records?: true
        )

      assert result.status == :success
      assert [record] = result.records
      assert is_nil(record.computed)
    end

    test "return_records?: false returns no records and still writes the rows" do
      result =
        Ash.bulk_create([%{name: "a"}], BulkReturnResource, :create,
          domain: BulkReturnDomain,
          return_records?: false
        )

      assert result.status == :success
      assert result.records == nil
      assert [[_id, _at, _naive, _day, "a", _computed]] = inserted_rows()
    end
  end
end
